# Sigmoid function
def sigmoid(x):
    return 1 / (1 + np.exp(-x))

# Derivative of sigmoid function
def derivatives_sigmoid(x):
    return x * (1 - x)

# Variable initialization
epoch = 5000
lr = 0.1
inputlayer_neurons = X.shape[1]
hiddenlayer_neurons = 3
output_neurons = 1

# Weight and bias initialization
wh = np.random.normal(loc=0.0, scale=1.0, size=(inputlayer_neurons, hiddenlayer_neurons))
bias_in = np.random.uniform(size=(1, hiddenlayer_neurons))
bh = np.tile(bias_in, (X.shape[0], 1))

wout = np.random.normal(loc=0.0, scale=1.0, size=(hiddenlayer_neurons, output_neurons))
bias_out = np.random.uniform(size=(1, output_neurons))
bout = np.tile(bias_out, (X.shape[0], 1))

# Forward propagation and backpropagation training
for i in range(epoch):
    # Forward Propagation
    hidden_layer_input1 = np.dot(X, wh)
    hidden_layer_input = hidden_layer_input1 + bh
    hidden_layer_activations = sigmoid(hidden_layer_input)
    output_layer_input1 = np.dot(hidden_layer_activations, wout)
    output_layer_input = output_layer_input1 + bout
    output = sigmoid(output_layer_input)

    # Back Propagation
    E = Y - output
    slope_output_layer = derivatives_sigmoid(output)
    slope_hidden_layer = derivatives_sigmoid(hidden_layer_activations)
    d_output = E * slope_output_layer
    Error_at_hidden_layer = np.dot(d_output, wout.T)
    d_hiddenlayer = Error_at_hidden_layer * slope_hidden_layer

    wout += np.dot(hidden_layer_activations.T, d_output) * lr
    bout += np.tile(np.sum(d_output, axis=0, keepdims=True), (X.shape[0], 1)) * lr
    wh += np.dot(X.T, d_hiddenlayer) * lr
    bh += np.tile(np.sum(d_hiddenlayer, axis=0, keepdims=True), (X.shape[0], 1)) * lr

print("Output from the model:")
print(output)

